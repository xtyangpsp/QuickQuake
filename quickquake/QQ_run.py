def check_settings(settings):
    """
    Return the settings to run with: the driver's settings, plus defaults for the missing
    ones. Stops if a required setting is missing; warns about misspelled and old settings.
    """
    # Only the driver's own settings: skip Python names (__file__ ...), imported modules,
    # functions and classes (Path, datetime ...).
    given = {k: v for k, v in settings.items()
             if not k.startswith("_")
             and not isinstance(v, (types.ModuleType, types.FunctionType, types.BuiltinFunctionType, type))}

    missing = [k for k in REQUIRED if k not in given]
    if missing:
        sys.exit(f"Your QQ_driver.py is missing these settings (they depend on your region): {', '.join(missing)}.\n"
                 "Copy them from quickquake/QQ_driver.py and set them for your project.")

    values = dict(given)
    used_defaults = [k for k in DEFAULTS if k not in given]
    for k in used_defaults:
        values[k] = DEFAULTS[k]

    # Old drivers wrote None for "use the default" here; the default for the radius
    # search was 3 attempts, 3 seconds apart.
    for k in ("download_max_retries", "download_retry_sleep"):
        if values[k] is None:
            values[k] = 3
            print(f"[settings] {k} = None -> 3 (the old default of the radius search)")

    # Settings computed from other settings, as in quickquake/QQ_driver.py
    if "BASE_DIR" not in values:
        values["BASE_DIR"] = Path(values["QUICKQUAKE_DIR"]).expanduser().resolve()
    if "DATA_ROOT" not in values:
        values["DATA_ROOT"] = Path(settings.get("__file__", "QQ_driver.py")).resolve().parent / "data"
    if "MODEL_DIR" not in values:
        values["MODEL_DIR"] = values["BASE_DIR"] / "dependencies/PhaseNet/model/190703-214543"
    if "location_templates_dir" not in values:
        values["location_templates_dir"] = values["BASE_DIR"] / "hypox_templates"

    if used_defaults:
        print("[settings] not in your driver, default used: "
              + ", ".join(f"{k} = {DEFAULTS[k]!r}" for k in used_defaults))
    known = set(REQUIRED) | set(DEFAULTS) | set(COMPUTED)
    for k in sorted(given):
        if k in OLD_SETTINGS:
            print(f"[settings] '{k}' is no longer used ({OLD_SETTINGS[k]}); it is ignored.")
        elif k not in known:
            close = difflib.get_close_matches(k, known, n=1)
            hint = f" Did you mean '{close[0]}'?" if close else ""
            print(f"[settings] WARNING: unknown setting '{k}' is ignored.{hint}")
    return values


def run(settings):
    """
    Run QuickQuake with the settings of a driver: QQ_driver.py calls run(globals()).

    The settings are copied into this module, so the code below reads them by the same
    names as in the driver (e.g. RUN_GAMMA, gamma_use_dbscan, center).
    """
    globals().update(check_settings(settings))
    global SCRIPTS
    SCRIPTS = {
        "config":      BASE_DIR / "quickquake/QQ_config.py",
        "stations":    BASE_DIR / "quickquake/QQ_dl_stations.py",
        "download":    BASE_DIR / "quickquake/QQ_dl_data.py",
        "phasenet":    BASE_DIR / "quickquake/QQ_predict.py",
        "gamma":       BASE_DIR / "quickquake/QQ_gamma.py",
        "merge":       BASE_DIR / "quickquake/QQ_merge_gamma_outputs.py",
        "arpick":      BASE_DIR / "quickquake/QQ_pick_arpick.py",
        "location":    BASE_DIR / "quickquake/QQ_location.py",
        "qc_velocity": BASE_DIR / "quickquake/QQ_qc.py",
    }
    main()


# HELPERS
